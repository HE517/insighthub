/**
 * The durable **document version history** seam (P0-1; `docs/agent-governance/P0-1-CONTRACTS.md`
 * C2/C4; `docs/DECISIONS.md` D-090).
 *
 * ## Why this is a capability next to `DocumentStore` and not a new frozen method
 *
 * `DocumentStore` (`docs/CONTRACTS.md` §14.1) is the *content reconstruction* seam: snapshot,
 * append-only log, compaction. A version row is a product-level snapshot with an author, a
 * title and a kind, and reading it must never be confused with replaying the log. Keeping it
 * in an interface of its own — exactly the pattern `DocumentMetaStore` and
 * `DocumentCreationStore` already use — means a test double that only wants to fault the log
 * does not have to grow a version API, and `app.ts` can take the read surface as an injectable
 * capability.
 *
 * ## What a version row is, precisely
 *
 * `yjs_state` is a **self-contained** encoded `Y.Doc` state (`Y.encodeStateAsUpdate`), never a
 * "sequence to replay from". That is what makes `pre-restore` survive log compaction and a
 * restart (`docs/ui/P0-RESTORE-DECISIONS.md` §3.3 "compaction 后" row).
 *
 * `sequence` is the **content revision** at capture time (`document_meta.content_revision`),
 * not the log position. This is the number a client compares in `baseRevision` (D-RC1), so a
 * join's empty update — which advances the log but not the body — cannot invalidate a preview.
 *
 * ## Kinds and retention (D-V2)
 *
 * | kind | written by | retention |
 * | --- | --- | --- |
 * | `auto` | the D-V2 capture in the document's FIFO slot: the first body change, then at most once per 10 minutes (`apps/server/src/versions/auto-version.ts`) | 30 days / 200 rows |
 * | `manual` | an explicit "save version" action (future) | 30 days / 200 rows |
 * | `pre-restore` | a restore, captured **before** it applies | **never auto-pruned** |
 * | `restored` | a restore, the new state after it applies | 30 days / 200 rows |
 *
 * The retention column is a *definition* for the future cleanup job, not code that runs here:
 * a `pre-restore` row is the only way back to the content a restore replaced, so pruning it
 * would delete the recovery entry point the product promises (`P0-RESTORE-DECISIONS.md` §1).
 *
 * **D-V2 (auto versions):** the policy lives in `versions/auto-version.ts` and is called by the
 * registry after a **committed** content-changing client update: the first change to a document
 * with no `auto` row is captured immediately, later ones only when the newest `auto` row is at
 * least 10 minutes old. The capture is best-effort — it runs after the append and after the
 * broadcast, and a failure is logged rather than allowed to fail the room or roll back the edit.
 * An idle document, an empty update and a repeated body produce no row because `contentChanged`
 * is false in each case. `captureDocumentVersion` reads `document_meta.content_revision` inside
 * its transaction, so the captured `sequence` is the same number `baseRevision` compares.
 */

/** The frozen version-kind vocabulary (C2). */
export const DOCUMENT_VERSION_KINDS = ['auto', 'manual', 'pre-restore', 'restored'] as const;

export type DocumentVersionKind = (typeof DOCUMENT_VERSION_KINDS)[number];

/** True for a value the schema's `CHECK (kind IN (...))` would accept. */
export function isDocumentVersionKind(value: unknown): value is DocumentVersionKind {
  return typeof value === 'string' && (DOCUMENT_VERSION_KINDS as readonly string[]).includes(value);
}

/** One version row as the API exposes it — never the `yjs_state` blob (C4). */
export interface DocumentVersionSummary {
  readonly id: string;
  /** Content revision at capture time (D-RC1's comparison number), not a log position. */
  readonly sequence: number;
  readonly title: string;
  readonly authorId: string;
  /** ISO 8601, like every other timestamp the API returns. */
  readonly createdAt: string;
  readonly kind: DocumentVersionKind;
}

/** A version plus its encoded state, for the restore path only. */
export interface StoredDocumentVersion extends DocumentVersionSummary {
  /** `Y.encodeStateAsUpdate` of the document at capture time. */
  readonly state: Uint8Array;
}

/** Input for a manual/auto capture. The id is generated by the store. */
export interface CaptureDocumentVersionInput {
  readonly documentId: string;
  readonly title: string;
  readonly authorId: string;
  /** Encoded state of the document **now**. */
  readonly state: Uint8Array;
  readonly kind: DocumentVersionKind;
  /** Injected clock so a test can assert ordering without sleeping. */
  readonly now?: number;
}

/** The version capability of the durable store (the SQLite store implements it). */
export interface DocumentVersionStore {
  /** Versions of one document, newest first (`sequence DESC, created_at DESC`). */
  listDocumentVersions(documentId: string): Promise<readonly DocumentVersionSummary[]>;

  /** One version **scoped to its document**, or `null`. Never crosses document ids. */
  readDocumentVersion(documentId: string, versionId: string): Promise<StoredDocumentVersion | null>;

  /**
   * Capture the current state as a new version row.
   *
   * This is the seam D-V2's auto capture (`rooms/registry.ts`, policy in
   * `versions/auto-version.ts`) and a future "save version" action use. Restore writes its rows
   * through `appendRestore` instead, so the two versions and the log row commit together; the
   * auto capture is deliberately a separate transaction *after* the edit's append has committed,
   * which is what makes it best-effort rather than part of the edit's durability.
   */
  captureDocumentVersion(input: CaptureDocumentVersionInput): Promise<DocumentVersionSummary>;

  /**
   * The document's current **content revision** (`document_meta.content_revision`).
   *
   * `0` for a document the store has never seen; a preview therefore records the same number a
   * restore compares against.
   */
  documentContentRevision(documentId: string): Promise<number>;
}

/** True when `value` can serve the version API (the SQLite store does). */
export function isDocumentVersionStore(value: unknown): value is DocumentVersionStore {
  if (typeof value !== 'object' || value === null) return false;
  const candidate = value as Partial<Record<keyof DocumentVersionStore, unknown>>;
  return (
    typeof candidate.listDocumentVersions === 'function' &&
    typeof candidate.readDocumentVersion === 'function' &&
    typeof candidate.captureDocumentVersion === 'function' &&
    typeof candidate.documentContentRevision === 'function'
  );
}
