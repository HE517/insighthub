/**
 * Collaborator presence UI: an overlapping avatar group in the document header.
 *
 * Every value rendered here comes from `CollaboratorInfo[]` — i.e. from
 * `session.getCollaborators()`, the schema-validated accessor. Nothing in this
 * file touches `session.awareness.getStates()`, so an unvalidated (or hostile)
 * peer payload can never reach the DOM as a name or a colour
 * (`AGENTS.md` R14, `docs/CONTRACTS.md` §9.2).
 *
 * ## Why the name is DOM text, not a `title` attribute
 *
 * `tests/browser/lib/app.mjs` `readCollaborators` reads `innerText` from the avatar's
 * ancestors, so a name hidden in `title=` or generated by CSS `content` would be invisible to
 * the browser suite — and, more importantly, to a screen reader. The name is a real text node
 * in the collaborator row; it is only *visually* revealed as a tooltip on hover/focus. The
 * element stays laid out (opacity, not `display: none`), so `innerText` contains it.
 *
 * ## Why the empty state is rendered inside the list
 *
 * The list container is a contract surface (`[data-testid="collaborator-list"]`) and must
 * exist even when nobody else is connected. The sentence "Only you are here" is the
 * established wording; `readCollaborators` uses it for its `emptyState` field.
 */
import type { CollaboratorInfo } from '@insighthub/shared';

import { colorForClient } from '../editor/remoteCursors.js';
import { initialsOf } from './collaboratorPresentation.js';

export interface CollaboratorListProps {
  collaborators: readonly CollaboratorInfo[];
  /** The local client id, so "you" is labelled instead of listed anonymously. */
  localClientId: number;
}

export function CollaboratorList({ collaborators, localClientId }: CollaboratorListProps) {
  return (
    <div
      className="collab-group"
      data-testid="collaborator-list"
      aria-label="Collaborators"
    >
      {collaborators.length === 0 ? (
        <span className="collab-group__empty">Only you are here</span>
      ) : (
        collaborators.map((collaborator) => {
          const color = collaborator.user.color ?? colorForClient(collaborator.clientId);
          const isSelf = collaborator.clientId === localClientId;
          return (
            <div
              className="collab"
              key={collaborator.clientId}
              data-client-id={collaborator.clientId}
              tabIndex={0}
            >
              <span
                className="collab__avatar"
                style={{ backgroundColor: color }}
                aria-hidden="true"
              >
                {initialsOf(collaborator.user.name)}
              </span>
              {/*
                The validated display name, as a text node inside the row. `readCollaborators`
                reads it; the tooltip styling only controls when it is painted.
              */}
              <span className="collab__tip">
                {collaborator.user.name}
                {isSelf ? ' · you' : ''}
              </span>
            </div>
          );
        })
      )}
    </div>
  );
}
